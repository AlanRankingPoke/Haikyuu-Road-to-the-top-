import assert from 'node:assert/strict';
import {courtFromCorners, calculateServe, pickCell} from './serve-math.mjs';
const court = courtFromCorners({x:0,y:0},{x:1200,y:600});
const left = calculateServe({x:900,y:300},100,court,100);
assert.equal(left.valid,true);
assert.deepEqual(left.cells, [{x:850,y:250},{x:950,y:250},{x:850,y:350},{x:950,y:350}]);
assert.deepEqual(pickCell(left.cells, () => 0.76),left.cells[3]);
const right = calculateServe({x:300,y:300},100,court,1100);
assert.equal(right.valid,true);
assert.equal(calculateServe({x:600,y:300},100,court,100).valid,false);
assert.equal(calculateServe({x:1150,y:300},100,court,100).valid,false);
assert.equal(calculateServe({x:900,y:10},100,court,100).valid,false);
assert.equal(calculateServe({x:300,y:300},100,court,100).valid,false);
console.log('✅ Testes da geometria do Saque por Baixo passaram.');
